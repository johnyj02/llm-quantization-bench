#!/usr/bin/env python3
r"""Generate H4's compliance-transition table from the analysis output. No number typed.

    .venv/bin/python scripts/make_h4_tables.py                     # main-v1

Reads  `artifacts/analysis/analysis_<run-id>.json`
Writes `paper/tables/h4_transitions.tex`, `paper/tables/h4_macros.tex`

WHY THIS EXISTS: same reason as `make_h3_tables.py` and `make_h8_tables.py` (R17.6.2).
Every statistic in the paper comes from a generated file, because this project has twice
put a superseded number in a table by hand-editing prose around a regenerated artifact.

⚠️ **SCOPE, per planner ruling R41.3.** H4 was cut from a full competence decomposition to
the **compliance-transition matrix only**. The decomposition rested on Manski bounds with
14 of 27 stratum cells below half and a three-item worst case, which invites *"your
decomposition is unidentified"*; the transition matrix needs no stratum and is a clean
finding. So this module deliberately does NOT emit competence components.

⚠️ **Measured at strict extraction.** `compliance` is a generation-level label
(§1.1 as amended, R26.3), and the transition matrix is computed at rung 1. That is stated
in the caption rather than left for a reader to infer.

🔬 **The finding the aggregate hides.** The off-diagonal traffic is large even where the
net is near zero: BBH GPTQ-4bit loses 423 committed answers and gains 421, a net of
$-0.06$ pp over 844 changed items. Reporting only the net would describe that cell as
unchanged. The `\hFour*Churn` macros exist so the prose can make that point with numbers.
"""

from __future__ import annotations

import argparse
import collections
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
TABLES = REPO / "paper" / "tables"

ARM_ORDER = ["gptq-8bit", "gptq-4bit", "awq-4bit", "bnb-nf4"]
ARM_LABEL = {
    "gptq-8bit": "GPTQ W8A16",
    "gptq-4bit": "GPTQ W4A16",
    "awq-4bit": "AWQ W4A16",
    "bnb-nf4": "bnb NF4",
}
TASK_ORDER = ["arc_challenge_chat", "bbh", "gsm8k_cot", "gsm8k"]
TASK_LABEL = {
    "arc_challenge_chat": "ARC-C",
    "bbh": "BBH",
    "gsm8k_cot": r"GSM8K\textsubscript{CoT}",
    "gsm8k": r"GSM8K\textsubscript{hash}",
}
#: §9c/R18.2 exclude the hash-marker arm from the registered families. It is shown as a
#: demonstration, so it is emitted but marked, never pooled into the headline counts.
DEMONSTRATION_ONLY = {"gsm8k"}


def arm_of(effect: dict) -> str:
    name = effect["name"]
    return name[name.index("[") + 1: name.index(" vs ")]


def aggregate(report: dict) -> dict:
    """(task, arm) -> counts pooled over models, plus how many effects exclude the null."""
    acc: dict = collections.defaultdict(
        lambda: {"n": 0, "lost": 0, "gained": 0, "sig": 0, "cells": 0})
    for e in report["transition_effects"]:
        c = e["context"]
        key = (c["cell"][1], arm_of(e))
        a = acc[key]
        a["n"] += e["n"]
        a["lost"] += c["n12"]        # committed under bf16, absent under the quantized arm
        a["gained"] += c["n21"]      # absent under bf16, committed under the quantized arm
        a["sig"] += int(bool(e.get("excludes_null")))
        a["cells"] += 1
        a["rung"] = c.get("rung")
    return acc


def transitions_table(report: dict) -> str:
    acc = aggregate(report)
    tasks = [t for t in TASK_ORDER if any(k[0] == t for k in acc)]
    rows = []
    for arm in ARM_ORDER:
        parts = []
        for task in tasks:
            a = acc.get((task, arm))
            if a is None:
                parts.append("-- & -- & --")
                continue
            net = (a["gained"] - a["lost"]) / a["n"] * 100 if a["n"] else 0.0
            churn = a["lost"] + a["gained"]
            net_s = f"{net:+.2f}"
            if a["sig"]:
                net_s = rf"\textbf{{{net_s}}}"
            parts.append(f"{churn} & {net_s} & {a['sig']}")
        rows.append(f"{ARM_LABEL[arm]} & " + " & ".join(parts) + r" \\")

    header = " & ".join(
        rf"\multicolumn{{3}}{{c}}{{{TASK_LABEL[t]}"
        + (r"$^{*}$" if t in DEMONSTRATION_ONLY else "")
        + "}"
        for t in tasks
    )
    return "\n".join([
        r"% GENERATED by scripts/make_h4_tables.py -- do not hand-edit",
        r"\begin{tabular}{l" + "rrc" * len(tasks) + "}",
        r"\toprule",
        "& " + header + r" \\",
        r"\cmidrule(lr){2-" + str(1 + 3 * len(tasks)) + "}",
        "arm & " + " & ".join([r"chg. & net & $\neq$0"] * len(tasks)) + r" \\",
        r"\midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabular}",
    ])


def macros(report: dict) -> str:
    acc = aggregate(report)
    te = report["transition_effects"]
    lines = [r"% GENERATED by scripts/make_h4_tables.py -- do not hand-edit"]

    def emit(name: str, value: str) -> None:
        lines.append(rf"\newcommand{{\hFour{name}}}{{{value}\xspace}}")

    emit("Effects", str(len(te)))
    emit("ExcludesNull", str(sum(1 for e in te if e.get("excludes_null"))))
    emit("Rung", str(next((e["context"].get("rung") for e in te), "strict")))

    # The cell that makes the churn point: largest |lost - gained| cancellation, i.e. the
    # most traffic hidden behind the smallest net. Chosen by a rule, not by eye.
    registered = {k: v for k, v in acc.items() if k[0] not in DEMONSTRATION_ONLY}
    # Selected by the rule "most off-diagonal traffic per unit of net movement", which is
    # exactly the claim being made: a large number of items changing state while the
    # aggregate barely moves. An earlier rule minimised |net| alone, which picked a cell
    # with half the traffic and so UNDERSTATED the point. The rule expresses the claim, so
    # it cannot be tuned by eye toward whichever cell looks best.
    best = max(registered.items(),
               key=lambda kv: (kv[1]["lost"] + kv[1]["gained"])
               / max(abs(kv[1]["gained"] - kv[1]["lost"]), 1))
    (task, arm), a = best
    net = (a["gained"] - a["lost"]) / a["n"] * 100
    emit("ChurnTask", TASK_LABEL[task])
    emit("ChurnArm", ARM_LABEL[arm])
    emit("ChurnLost", str(a["lost"]))
    emit("ChurnGained", str(a["gained"]))
    emit("ChurnTotal", str(a["lost"] + a["gained"]))
    emit("ChurnNet", f"{net:+.2f}")

    # The largest movements in each direction, again by rule.
    gains = max(registered.items(),
                key=lambda kv: (kv[1]["gained"] - kv[1]["lost"]) / max(kv[1]["n"], 1))
    losses = min(registered.items(),
                 key=lambda kv: (kv[1]["gained"] - kv[1]["lost"]) / max(kv[1]["n"], 1))
    for tag, ((t, ar), v) in (("Gain", gains), ("Loss", losses)):
        emit(tag + "Task", TASK_LABEL[t])
        emit(tag + "Arm", ARM_LABEL[ar])
        emit(tag + "Net", f"{(v['gained'] - v['lost']) / v['n'] * 100:+.2f}")

    strat = report.get("stratum") or []
    low = [s for s in strat if (s.get("fraction_of_paired") or 1.0) < 0.5]
    emit("StratumCells", str(len(strat)))
    emit("StratumBelowHalf", str(len(low)))
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate H4's tables")
    parser.add_argument("--run-id", default="main-v1")
    args = parser.parse_args()
    path = REPO / "artifacts" / "analysis" / f"analysis_{args.run_id}.json"
    if not path.is_file():
        raise SystemExit(f"missing {path}; run scripts/analyze_run.py first")
    report = json.loads(path.read_text())
    if report.get("run_id") != args.run_id:
        raise SystemExit(
            f"{path} reports run_id={report.get('run_id')!r}; refusing to emit tables "
            f"from the wrong run")
    TABLES.mkdir(parents=True, exist_ok=True)
    for name, body in {
        "h4_transitions.tex": transitions_table(report),
        "h4_macros.tex": macros(report),
    }.items():
        (TABLES / name).write_text(body + "\n")
        print(f"  wrote paper/tables/{name}  ({len(body.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
