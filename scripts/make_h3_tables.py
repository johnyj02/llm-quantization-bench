#!/usr/bin/env python3
r"""Generate H3's LaTeX tables from the analysis output. No number is typed by hand.

    .venv/bin/python scripts/make_h3_tables.py                     # main-v1
    .venv/bin/python scripts/make_h3_tables.py --run-id pilot-v2

Reads  `artifacts/analysis/analysis_<run-id>.json`
Writes `paper/tables/h3_interaction.tex`, `h3_heterogeneity.tex`, `h3_macros.tex`

WHY THIS EXISTS, and it is the same reason `make_h8_tables.py` does (R17.6.2). Every
statistic in the paper must be sourced from a generated file rather than inlined, because
this project has twice put a superseded number in a table by hand-editing prose around a
regenerated artifact, and once nearly reported a figure the pre-registration forbade.
H3's numbers are especially prone to it: they have already been revised twice in one day,
once because our own rung-2 parser was missing the unit stripping `A5` registers, which
turned a significant positive effect into a null with the opposite sign.

⚠️ **Do not hand-edit the emitted files, and do not inline a number that lives here.**
Re-run this after any re-analysis.

⚠️ **`gsm8k` is EXCLUDED from the registered interaction** (§9c, planner ruling R18.2): a
1% strict score is a floor, and a floored metric has no variance for an interaction to
appear in. It is emitted separately as `\hThreeGsmDemo*` macros so the prose can cite it
as a demonstration without it ever entering the Holm family. The exclusion is read from
the analysis output rather than hardcoded, so the two cannot disagree.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
TABLES = REPO / "paper" / "tables"

#: Display order, coarsest precision last, matching every other table in the paper.
ARM_ORDER = ["gptq-8bit", "gptq-4bit", "awq-4bit", "bnb-nf4"]
ARM_LABEL = {
    "gptq-8bit": "GPTQ W8A16",
    "gptq-4bit": "GPTQ W4A16",
    "awq-4bit": "AWQ W4A16",
    "bnb-nf4": "bnb NF4",
}
#: Task display order: constrained control first, then the two generative tasks.
TASK_ORDER = ["arc_challenge_chat", "bbh", "gsm8k_cot"]
TASK_LABEL = {
    "arc_challenge_chat": r"ARC-C (gen.)",
    "bbh": "BBH",
    "gsm8k_cot": r"GSM8K\textsubscript{CoT}",
}


def arm_of(effect: dict) -> str:
    """`H3_interaction_marginal[gptq-4bit vs bf16]` -> `gptq-4bit`."""
    name = effect["name"]
    return name[name.index("[") + 1: name.index(" vs ")]


def fmt(value: float, places: int = 2) -> str:
    return f"{value:+.{places}f}"


def interaction_table(report: dict) -> str:
    """Per (task, arm) interaction in accuracy points, with the interval and n.

    ⚠️ ARC's rows are a **worst-case bound**, not a bootstrap interval, and the two are
    different objects that R26.1 forbade reading against each other. The `interval_method`
    field distinguishes them in the artifact, and the table marks them with a dagger so the
    distinction survives into the paper.
    """
    by_key = {
        (e["context"]["task"], arm_of(e)): e for e in report["h3_interaction"]
    }
    tasks = [t for t in TASK_ORDER if any(k[0] == t for k in by_key)]

    rows = []
    for arm in ARM_ORDER:
        cells = []
        for task in tasks:
            e = by_key.get((task, arm))
            if e is None:
                cells.append(r"\multicolumn{2}{c}{--}")
                continue
            bound = e["context"].get("zero_variance")
            est = fmt(e["estimate"])
            interval = f"[{fmt(e['ci_low'])}, {fmt(e['ci_high'])}]"
            if bound:
                est += r"$^{\dagger}$"
            elif e.get("excludes_null"):
                est = rf"\textbf{{{est}}}"
            cells.append(f"{est} & {interval}")
        rows.append(f"{ARM_LABEL[arm]} & " + " & ".join(cells) + r" \\")

    header = " & ".join(
        rf"\multicolumn{{2}}{{c}}{{{TASK_LABEL[t]} ($n$={by_key[(t, ARM_ORDER[0])]['n']:,})}}"
        for t in tasks
    )
    return "\n".join([
        r"% GENERATED by scripts/make_h3_tables.py -- do not hand-edit",
        r"\begin{tabular}{l" + "rc" * len(tasks) + "}",
        r"\toprule",
        "& " + header + r" \\",
        r"\cmidrule(lr){2-" + str(1 + 2 * len(tasks)) + "}",
        "arm & " + " & ".join([r"est. & 95\% CI"] * len(tasks)) + r" \\",
        r"\midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabular}",
    ])


def heterogeneity_table(report: dict) -> str:
    """§2a's two pre-specified contrasts, with their Holm-adjusted decisions.

    These are what turn "the sign differs by task" from an observation into a test. R41.4
    was explicit that the sign disagreement is an asset only if this is computed; unrun, it
    is the *"unstable result our parser moved twice"* liability instead.
    """
    holm = {r["name"]: r for r in report["h3_heterogeneity_holm"]["rows"]}
    rows = []
    for e in report["h3_heterogeneity"]:
        r = holm.get(e["name"], {})
        inner = e["name"][e["name"].index("[") + 1:].rstrip("]")
        kind, _, detail = inner.partition("[")
        decision = r"\textbf{reject}" if r.get("rejected") else "retain"
        # ⚠️ Raw identifiers must NOT reach LaTeX. `gsm8k_cot` contains an underscore,
        # which is a subscript operator in math mode and a hard error in text mode, so the
        # first version of this table would not compile. Mapped through the display labels
        # that the rest of the paper already uses, which also keeps the two consistent.
        levels = detail.rstrip("]")
        for raw, shown in TASK_LABEL.items():
            levels = levels.replace(raw, shown)
        for raw, shown in ARM_LABEL.items():
            levels = levels.replace(raw, shown)
        rows.append(
            f"{kind.replace('_', ' ')} & {levels} & "
            f"{fmt(e['estimate'])} & [{fmt(e['ci_low'])}, {fmt(e['ci_high'])}] & "
            f"{e['n']:,} & {r.get('adjusted_alpha', float('nan')):.3f} & {decision}" + r" \\"
        )
    return "\n".join([
        r"% GENERATED by scripts/make_h3_tables.py -- do not hand-edit",
        r"\begin{tabular}{llrcrrl}",
        r"\toprule",
        r"contrast & levels & est. & 95\% CI & $n$ & $\alpha_{\text{Holm}}$ & decision \\",
        r"\midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabular}",
    ])


def macros(report: dict) -> str:
    """Single-number facts the prose needs, so the prose cannot go stale."""
    by_key = {
        (e["context"]["task"], arm_of(e)): e for e in report["h3_interaction"]
    }
    lines = [r"% GENERATED by scripts/make_h3_tables.py -- do not hand-edit"]

    def emit(name: str, value: str) -> None:
        lines.append(rf"\newcommand{{\hThree{name}}}{{{value}\xspace}}")

    emit("Rows", str(len(report["h3_interaction"])))
    emit("Records", f"{report['n_rows']:,}")

    # The registered per-cell estimates the prose quotes directly.
    short = {"bbh": "Bbh", "gsm8k_cot": "Gsm", "arc_challenge_chat": "Arc"}
    # ⚠️ NO DIGITS. A LaTeX macro name may contain only letters, so `\hThreeArcNf4` is a
    # hard "Missing \begin{document}" error at \input time rather than an undefined-macro
    # warning. Digits are spelled out here for that reason, not for style.
    tag = {"gptq-8bit": "GptqEight", "gptq-4bit": "GptqFour",
           "awq-4bit": "Awq", "bnb-nf4": "NfFour"}
    for (task, arm), e in by_key.items():
        if task not in short:
            continue
        stem = short[task] + tag[arm]
        emit(stem, fmt(e["estimate"]))
        emit(stem + "Lo", fmt(e["ci_low"]))
        emit(stem + "Hi", fmt(e["ci_high"]))

    # ARC's bound is one number shared by all four arms, so name it once.
    arc = next((e for e in report["h3_interaction"]
                if e["context"]["task"] == "arc_challenge_chat"), None)
    if arc is not None:
        emit("ArcBound", f"{arc['ci_high']:.2f}")
        emit("ArcN", f"{arc['n']:,}")

    # How many registered cells exclude the null, counted rather than recalled.
    excl = sum(1 for e in report["h3_interaction"] if e.get("excludes_null"))
    emit("ExcludesNull", str(excl))
    emit("HolmM", str(report["h3_holm"]["m"]))

    for e in report["h3_heterogeneity"]:
        which = "Tasks" if "across_tasks" in e["name"] else "Arms"
        emit("Het" + which, fmt(e["estimate"]))
        emit("Het" + which + "Lo", fmt(e["ci_low"]))
        emit("Het" + which + "Hi", fmt(e["ci_high"]))

    # The excluded demonstration arm (§9c). Emitted so the prose can cite it WITHOUT it
    # ever entering the Holm family, and read from the output so the two cannot disagree.
    demo = {arm_of(e): e for e in report.get("h3_interaction_demonstration_only", [])}
    if demo:
        emit("GsmDemoExcluded", ", ".join(report["h3_excluded_tasks"]))
        for arm, e in demo.items():
            emit("GsmDemo" + tag[arm], fmt(e["estimate"]))
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate H3's tables")
    parser.add_argument("--run-id", default="main-v1")
    args = parser.parse_args()

    path = REPO / "artifacts" / "analysis" / f"analysis_{args.run_id}.json"
    if not path.is_file():
        raise SystemExit(
            f"missing {path}\n"
            f"run: .venv/bin/python scripts/analyze_run.py --run-id {args.run_id}"
        )
    report = json.loads(path.read_text())
    if report.get("run_id") != args.run_id:
        raise SystemExit(
            f"{path} reports run_id={report.get('run_id')!r}, expected {args.run_id!r}; "
            f"refusing to emit tables from the wrong run"
        )
    TABLES.mkdir(parents=True, exist_ok=True)

    for name, body in {
        "h3_interaction.tex": interaction_table(report),
        "h3_heterogeneity.tex": heterogeneity_table(report),
        "h3_macros.tex": macros(report),
    }.items():
        (TABLES / name).write_text(body + "\n")
        print(f"  wrote paper/tables/{name}  ({len(body.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
